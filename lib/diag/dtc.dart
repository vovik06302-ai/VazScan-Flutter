import 'dtc_raw.dart';

class DtcInfo {
  final String code;
  final int severity;
  final String title;
  final List<String> causes;
  final List<String> steps;
  const DtcInfo(this.code, this.severity, this.title, this.causes, this.steps);
}

class DtcDb {
  static final Map<String, DtcInfo> _map = _build();

  static DtcInfo lookup(String code) {
    final c = code.toUpperCase();
    return _map[c] ?? _generic(c);
  }

  static List<String> _list(String s) => s.split(';').map((e) => e.trim()).where((e) => e.isNotEmpty).toList();

  static Map<String, DtcInfo> _build() {
    final m = <String, DtcInfo>{};
    for (final line in dtcRaw.split('\n')) {
      if (line.trim().isEmpty) continue;
      final p = line.split('|');
      if (p.length < 5) continue;
      final code = p[0].trim();
      m[code] = DtcInfo(code, int.parse(p[1].trim()), p[2].trim(), _list(p[3]), _list(p[4]));
    }
    for (var n = 1; n <= 4; n++) {
      m['P020$n'] = DtcInfo(
        'P020$n', 2, 'Цепь форсунки цилиндра $n',
        _list('Обрыв или замыкание провода форсунки;Нет питания на форсунке (реле, предохранитель);Неисправна форсунка;Плохой контакт в колодке'),
        _list('Проверить колодку и провода форсунки;Измерить сопротивление обмотки форсунки (обычно около 12-16 Ом);Переставить форсунку в другой цилиндр: если код перешёл, неисправна форсунка;Проверить напряжение питания форсунок при включённом зажигании'),
      );
      m['P030$n'] = DtcInfo(
        'P030$n', 3, 'Пропуски зажигания в цилиндре $n',
        _list('Неисправна свеча или высоковольтный провод;Неисправен модуль зажигания;Неисправна или засорена форсунка;Подсос воздуха;Низкая компрессия или проблема с клапаном'),
        _list('Заменить или переставить свечу этого цилиндра: если пропуски переехали, виновата свеча;Проверить высоковольтный провод и наконечник;Проверить форсунку цилиндра;Измерить компрессию (около 11-13 кг/см², разброс не более 1);Не ехать с мигающей лампой Check Engine'),
      );
      m['P035$n'] = DtcInfo(
        'P035$n', 3, 'Цепь катушки или канала модуля зажигания (цилиндр $n)',
        _list('Неисправен модуль зажигания (частая причина у ВАЗ);Обрыв или замыкание проводов к модулю;Нет питания 12 В или плохая масса модуля;Редко: неисправен ЭБУ'),
        _list('Проверить питание и массу на разъёме модуля зажигания;Осмотреть колодку и провода на окисление;Проверить сопротивление первичных обмоток модуля;Для проверки поставить заведомо исправный модуль'),
      );
    }
    const inj = [
      ['P0261', '1', 'low'], ['P0262', '1', 'high'], ['P0264', '2', 'low'], ['P0265', '2', 'high'],
      ['P0267', '3', 'low'], ['P0268', '3', 'high'], ['P0270', '4', 'low'], ['P0271', '4', 'high'],
    ];
    for (final e in inj) {
      final low = e[2] == 'low';
      m[e[0]] = DtcInfo(
        e[0], 2,
        low
            ? 'Низкий уровень сигнала цепи форсунки цилиндра ${e[1]} (замыкание на массу)'
            : 'Высокий уровень сигнала цепи форсунки цилиндра ${e[1]} (обрыв или замыкание на питание)',
        _list(low
            ? 'Замыкание провода форсунки на массу;Межвитковое замыкание в форсунке;Неисправен драйвер в ЭБУ'
            : 'Обрыв провода или обмотки форсунки;Замыкание на питание;Окисление контактов колодки'),
        _list('Проверить провода и колодку форсунки;Измерить сопротивление обмотки (обычно около 12-16 Ом);Заменить форсунку при отклонении от нормы'),
      );
    }
    return m;
  }

  static DtcInfo _generic(String c) {
    String sys;
    if (c.startsWith('P1')) {
      sys = 'код производителя';
    } else if (c.startsWith('C')) {
      sys = 'шасси (тормоза, ABS)';
    } else if (c.startsWith('B')) {
      sys = 'кузовная электроника';
    } else if (c.startsWith('U')) {
      sys = 'обмен данными между блоками';
    } else if (c.length >= 3 && (c.startsWith('P0') || c.startsWith('P2'))) {
      switch (c[2]) {
        case '0':
        case '1':
        case '2':
          sys = 'топливо и воздух';
          break;
        case '3':
          sys = 'зажигание и пропуски';
          break;
        case '4':
          sys = 'системы снижения токсичности';
          break;
        case '5':
          sys = 'скорость и холостой ход';
          break;
        case '6':
          sys = 'блок управления и его цепи';
          break;
        default:
          sys = 'трансмиссия';
      }
    } else {
      sys = 'не определена';
    }
    return DtcInfo(
      c, 2, 'Код $c: подробного описания в базе нет (система: $sys)',
      _list('Точная причина зависит от модели блока управления (Январь 5.1 / 7.2, Bosch M7.9.7, Itelma и др.)'),
      _list('Найти расшифровку кода именно для вашего блока;Проверить цепи, колодки и массы соответствующего датчика или исполнительного устройства;Сбросить ошибку и посмотреть, возвращается ли она;Если код возвращается сразу, продиагностировать узел детально'),
    );
  }
}
